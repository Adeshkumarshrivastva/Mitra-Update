# Words that turn a feeling into a denial ("चिंता नहीं है") so the model handles it instead.
NEGATIONS = ("nahi", "nahin", "नहीं", "नही", "ठीक हूँ", "ठीक हूं", "theek hoon", "theek hu", "बिल्कुल ठीक")

_SPACES = re.compile(r"\s+")


def _normalize(text: str) -> str:
    return _SPACES.sub(" ", str(text or "").lower()).strip()


def match_topic(text: str, seen: set[str] | None = None, allowed: set[str] | None = None) -> Topic | None:
    """The topic the driver is talking about, or None to let the model answer.

    A topic already answered in this conversation is skipped, so a repeated word never replays the same scripted reply.
    Long messages and denials such as "चिंता नहीं है" are left to the model too. When `allowed` is given, only those
    topics can match (after a Mind Check the model answers questions about the result).
    """
    normalized = _normalize(text)
    if not normalized or len(normalized.split()) > 25:
        return None
    denied = any(word in normalized for word in NEGATIONS)
    for topic in TOPICS:
        if seen and topic.name in seen:
            continue
        if allowed is not None and topic.name not in allowed:
            continue
        if any(keyword in normalized for keyword in topic.keywords):
            if denied and not topic.negation_ok:
                return None
            return topic
    return None


SAFETY_TOPICS = {"crisis", "emergency", "panic", "thanks", "bye"}


def pick_reply(topic: Topic) -> str:
    return random.choice(topic.replies)


def idle_nudge(count: int) -> str:
    return IDLE_NUDGES[count % len(IDLE_NUDGES)]


